/**
 * 卡片块的格式说明。
 *
 * 这段是**唯一**告诉模型「有卡片这回事」的地方。它必须同时说清三件事，
 * 少一件模型就会用错：
 *   1. 什么时候用（清单里的判据）
 *   2. 具体写成什么样（标记 + JSON 的形态，各类型的字段名）
 *   3. 什么时候**不用** —— 最容易漏的一条，漏了它每句话都会套卡
 */
export function cardContract() {
  return `# 群回复的卡片

群里的回复可以有两种形态：**一段纯文本**，或**一张卡片**。

什么时候用卡片：下面清单里能对上判据的，就用卡片。理由不是好看 ——
卡片把「结论」「边界」「证据」「内部记录」固定在各自的格子里，
你想多写一句，都能看出是哪个格子变胖了。表格也只有卡片里才是表格
（纯文本发出去的竖线表格，在群里就是一堆 \`|\`）。

什么时候不用：**一句话能答完的，就一句话答完**，别套卡。
「收到」「好」「我在查」这类不需要结构，写成卡片反而占一屏。

## 怎么写

先正常写你的回答。如果要用卡片，就在**最后**加一个卡片块，形态是：

\`\`\`
[[card:类型]]
{"title":"卡片标题","verdict":"结论","boundary":"可选的一行边界"}
\`\`\`

规则：

- 标记后面必须紧跟一个 JSON 对象。**块之外不要重复写正文** ——
  如果你在块外也写了话，那些话会被塞进折叠区，群里会看到「卡 + 一段重复的话」。
- 字段名必须用下面清单里的字段。**没有的字段不要编**，编了整张卡会被拒。
- 结论字段（\`verdict\`）一句话，**不超过 60 个字符**。写不下说明结论还没提炼出来，
  先去查清楚再答 —— 超过的部分会被挪到边界格，不要指望它留在结论里。
- **结论是你查到的事实，不是你打算怎么排版。** 写「按三栏分，不解释原因」是给
  自己的指令，对方看了还是不知道答案；写「本群可见窗口内你发过 11 条」才是结论。
  标题（\`title\`）同理：写结论本身，不写「关于 X 的答复」。
- 边界字段（\`boundary\`）只写一行，**不超过 90 个字符**，没有就不填。
  不要写「本回答基于…」这种模板句。
- 内部记录（工具名、调用次数、栈、耗时、token 数）**只能进折叠区**的字段
  （\`internal\` / \`evidence\` / \`tried\`），永远不许出现在正文格子里。

## 十一个类型

${menuForPrompt()}

## 各类型的字段

${REGISTRY.map((r) => {
  const fields = Object.entries(r.fields)
    .map(([k, v]) => `${k}（${v.split('。')[0]}）`)
    .join(' · ');
  return `- \`${r.kind}\`：${fields}`;
}).join('\n')}

如果卡片构建失败，会退化成纯文本发出去，对方看到的是你写的正文。
所以**写坏了不会丢话**，但会丢格式 —— 想清楚再选类型。`;
}

/** 构建一条完整的 system message（未来若要注入动态上下文，加在这里） */
export function buildSystemPrompt(extra = '') {
  const now = new Date().toLocaleString('zh-CN', { timeZone: 'Asia/Shanghai', hour12: false });
  return `${SYSTEM_PROMPT}\n\n${cardContract()}\n\n# 当前时间\n${now}（Asia/Shanghai）${extra ? `\n\n${extra}` : ''}`;
}
