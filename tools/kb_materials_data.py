KB_CLASSES = ("外部标准库", "内部正面与负面样本库", "措辞表达库", "产品描述库")
NATURES = ("知识材料", "任务系统", "需求框架", "方案文档", "内容资产", "空行")


def readable():
    """实测可读性统计。**全部现算** —— 散文里不许再写这几个数（B3.0/15.4）。"""
    ok = sum(1 for m in MATERIALS if m["可读性"] == "ok")
    return {"total": len(MATERIALS), "readable": ok, "unreadable": len(MATERIALS) - ok,
            "perm": sum(1 for m in MATERIALS if m["可读性"] == "perm"),
            "bad": sum(1 for m in MATERIALS if m["可读性"] == "bad")}


def by_class():
    out = {k: [] for k in KB_CLASSES}
    for m in MATERIALS:
        if m["归属知识库"] in out:
            out[m["归属知识库"]].append(m)
    return out


def unclassified():
    """还需要人来定的材料。B3.2 之后这个集合应当是空的 —— 空不是「没人管」，
    是「每一条都被明确回答过」（包括回答「它就不是知识材料」）。"""
    return [m for m in MATERIALS
            if m["材料性质"] not in NATURES
            or m["归属知识库"] not in KB_CLASSES + ("—",)]


